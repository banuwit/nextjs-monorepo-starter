import type { Metadata } from "next";
import localFont from "next/font/local";
import "./globals.css";
import { cookies } from "next/headers";
import { cn } from "@/lib/utils";
import {
  readPreferences,
  preferencesBootScript,
  preferenceColorStyle,
} from "@/lib/preferences-config";
import { PreferencesProvider } from "@/providers/preferences-provider";

const inter = localFont({
  src: "./fonts/Inter-latin.woff2",
  weight: "100 900",
  variable: "--font-inter",
  preload: false,
});
const nunito = localFont({
  src: "./fonts/Nunito-latin.woff2",
  weight: "200 1000",
  variable: "--font-nunito",
  preload: false,
});
const roboto = localFont({
  src: "./fonts/Roboto-latin.woff2",
  weight: "100 900",
  variable: "--font-roboto",
  preload: false,
});
const dmSans = localFont({
  src: "./fonts/DMSans-latin.woff2",
  weight: "100 1000",
  variable: "--font-dm-sans",
  preload: false,
});
const poppins = localFont({
  src: [
    { path: "./fonts/Poppins-400-latin.woff2", weight: "400" },
    { path: "./fonts/Poppins-500-latin.woff2", weight: "500" },
    { path: "./fonts/Poppins-600-latin.woff2", weight: "600" },
    { path: "./fonts/Poppins-700-latin.woff2", weight: "700" },
  ],
  variable: "--font-poppins",
  preload: false,
});
const raleway = localFont({
  src: "./fonts/Raleway-latin.woff2",
  weight: "100 900",
  variable: "--font-raleway",
  preload: false,
});

const geistSans = localFont({
  src: "./fonts/GeistVF.woff",
  variable: "--font-geist-sans",
});
const geistMono = localFont({
  src: "./fonts/GeistMonoVF.woff",
  variable: "--font-geist-mono",
});

export const metadata: Metadata = {
  title: "Create Next App",
  description: "Generated by create next app",
};

export default async function RootLayout({
  children,
}: Readonly<{
  children: React.ReactNode;
}>) {
  const values = readPreferences((await cookies()).toString());
  return (
    <html
      lang="en"
      className={cn(
        "font-sans",
        geistSans.variable,
        geistMono.variable,
        inter.variable,
        nunito.variable,
        roboto.variable,
        dmSans.variable,
        poppins.variable,
        raleway.variable,
        values.themeMode === "dark" && "dark",
      )}
      data-theme-mode={values.themeMode}
      data-font={values.font}
      data-content-layout={values.contentLayout}
      data-sidebar-style={values.sidebarStyle}
      data-primary-color={values.primaryColor}
      data-sidebar-color={values.sidebarColor}
      data-header-color={values.headerColor}
      data-app-body-color={values.appBodyColor}
      data-border-radius={values.borderRadius}
      data-scale={values.scale}
      style={
        {
          ...preferenceColorStyle("primaryColor", values.primaryColor),
          ...preferenceColorStyle("sidebarColor", values.sidebarColor),
          ...preferenceColorStyle("headerColor", values.headerColor),
          ...preferenceColorStyle("appBodyColor", values.appBodyColor),
        } as React.CSSProperties
      }
      suppressHydrationWarning
    >
      <head>
        <script
          dangerouslySetInnerHTML={{
            __html: preferencesBootScript(values),
          }}
        />
      </head>
      <body>
        <PreferencesProvider initialValues={values}>
          {children}
        </PreferencesProvider>
      </body>
    </html>
  );
}
